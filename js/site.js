  function t(lang, key) {
    var pack = I18N[lang] || I18N.en;
    if (pack[key] != null) return pack[key];
    return I18N.en[key] != null ? I18N.en[key] : "";
  }

  function readLang() {
    try {
      return localStorage.getItem("kaneff-lang");
    } catch (err) {
      return null;
    }
  }

  function storeLang(lang) {
    try {
      localStorage.setItem("kaneff-lang", lang);
    } catch (err) {
      /* private mode */
    }
  }

  function apply(lang) {
    if (lang !== "bg" && lang !== "en") lang = "en";
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(lang, el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      el.alt = t(lang, el.dataset.i18nAlt);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(lang, el.dataset.i18nAria));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.placeholder = t(lang, el.dataset.i18nPlaceholder);
    });

    var titleEl = document.querySelector("title[data-i18n]");
    if (titleEl) document.title = t(lang, titleEl.dataset.i18n);
    document.querySelectorAll("[data-i18n-content]").forEach(function (el) {
      el.setAttribute("content", t(lang, el.dataset.i18nContent));
    });
    document.querySelectorAll("[data-gallery]").forEach(function (img) {
      img.alt = t(lang, "gallery.alt." + img.dataset.gallery).replace("{n}", img.dataset.n || "");
    });

    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
    });

    var status = document.getElementById("lang-status");
    if (status) status.textContent = t(lang, "lang.status");
    storeLang(lang);
  }

  function currentLang() {
    return document.documentElement.lang === "bg" ? "bg" : "en";
  }

  var header = document.querySelector(".site-header");
  var nav = document.getElementById("site-nav");
  var toggle = document.querySelector(".nav-toggle");

  function setMenu(open) {
    if (!nav || !toggle) return;
    nav.classList.toggle("is-open", open);
    toggle.setAttribute("aria-expanded", open ? "true" : "false");
    var label = toggle.querySelector(".sr-only");
    if (label) {
      label.dataset.i18n = open ? "nav.close" : "nav.menu";
      label.textContent = t(currentLang(), label.dataset.i18n);
    }
  }

  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    btn.addEventListener("click", function () {
      apply(btn.dataset.lang);
    });
  });

  if (toggle && nav) {
    toggle.addEventListener("click", function () {
      var open = toggle.getAttribute("aria-expanded") !== "true";
      setMenu(open);
    });
    nav.addEventListener("click", function (event) {
      if (event.target.closest("a")) setMenu(false);
    });
    document.addEventListener("click", function (event) {
      if (header && !header.contains(event.target)) setMenu(false);
    });
    document.addEventListener("keydown", function (event) {
      if (event.key === "Escape") setMenu(false);
    });
    window.addEventListener("resize", function () {
      if (window.innerWidth > 1180) setMenu(false);
    });
  }

